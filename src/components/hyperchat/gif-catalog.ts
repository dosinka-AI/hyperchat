export function searchCatalog(q: string): typeof GIF_CATALOG {
  const query = q.trim().toLowerCase()
  if (!query) return GIF_CATALOG
  const tokens = query.split(/\s+/).filter(Boolean)
  const haystacks = GIF_CATALOG.map((gif) => `${gif.title} ${gif.tags.join(' ')}`.toLowerCase())
  const strict = GIF_CATALOG.filter((_, i) => tokens.every((token) => haystacks[i].includes(token)))
  if (strict.length > 0) return strict
  return GIF_CATALOG.filter((_, i) => tokens.some((token) => haystacks[i].includes(token)))
}
